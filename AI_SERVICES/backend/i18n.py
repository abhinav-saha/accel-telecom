def label(row: tuple, lang: str) -> str:
    idx = {"en": 1, "hi": 2, "mr": 3}.get(lang, 1)
    return row[idx]


def q(key: str, lang: str, **kw) -> str:
    bank = Q[key]
    text = bank.get(lang) or bank.get("hi" if lang in ("hi", "mr") else "en") or bank["en"]
    return text.format(**kw) if kw else text
